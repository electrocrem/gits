local function terminal_colors()
  local t = {
    c.bg_hl, c.red, c.green, c.yellow, c.blue, c.purple, c.cyan, c.fg_dim,
    c.cyan_lo, c.red_hi, c.green_hi, c.yellow_hi, c.blue_hi, c.purple_hi, c.cyan_hi, c.white,
  }
  for i, color in ipairs(t) do
    vim.g["terminal_color_" .. (i - 1)] = color
  end
end

function M.load()
  vim.cmd("hi clear")
  if vim.fn.exists("syntax_on") == 1 then
    vim.cmd("syntax reset")
  end
  vim.o.termguicolors = true
  vim.o.background = "dark"
  vim.g.colors_name = "gits"

  for name, spec in pairs(groups()) do
    if type(spec) == "string" then
      vim.api.nvim_set_hl(0, name, { link = spec })
    else
      vim.api.nvim_set_hl(0, name, spec)
    end
  end
  terminal_colors()
end

M.palette = c

return M
